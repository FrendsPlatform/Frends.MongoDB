using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.IO;
using System.Threading;
using System.Threading.Tasks;
using Frends.MongoDB.Insert.Definitions;
using Frends.MongoDB.Insert.Helpers;
using MongoDB.Bson;
using MongoDB.Driver;

namespace Frends.MongoDB.Insert;

/// <summary>
/// MongoDB Task.
/// </summary>
public static class MongoDB
{
    /// <summary>
    /// MongoDB insert operation.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.MongoDB.Insert)
    /// </summary>
    /// <param name="input">Input parameters.</param>
    /// <param name="connection">Connection parameters.</param>
    /// <param name="options">Additional parameters.</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this task.</param>
    /// <returns>object { bool Success, List&lt;string&gt; Id, object Error { string Message, Exception AdditionalInfo } }</returns>
    public static async Task<Result> Insert(
        [PropertyTab] Input input,
        [PropertyTab] Connection connection,
        [PropertyTab] Options options,
        CancellationToken cancellationToken)
    {
        try
        {
            var collection = GetMongoCollection(
                connection.ConnectionString,
                connection.Database,
                connection.CollectionName);
            var ids = new List<string>();

            switch (input.InputType)
            {
                case InputType.File:
                    var fileContent = await File.ReadAllTextAsync(input.File, cancellationToken);
                    var fileDocument = BsonDocument.Parse(fileContent);
                    await collection.InsertOneAsync(fileDocument, cancellationToken: cancellationToken);
                    ids.Add(fileDocument["_id"].ToString());
                    return new Result(true, ids);

                case InputType.Document:
                    var doc = BsonDocument.Parse(input.Document);
                    await collection.InsertOneAsync(doc, cancellationToken: cancellationToken);
                    ids.Add(doc["_id"].ToString());
                    return new Result(true, ids);

                case InputType.Documents:
                    foreach (var document in input.Documents)
                    {
                        var docs = BsonDocument.Parse(document.Value);
                        await collection.InsertOneAsync(docs, cancellationToken: cancellationToken);
                        ids.Add(docs["_id"].ToString());
                    }

                    return new Result(true, ids);

                default:
                    return new Result(false, null);
            }
        }
        catch (Exception ex)
        {
            return ex.Handle(options);
        }
    }

    private static IMongoCollection<BsonDocument> GetMongoCollection(
        string connectionString,
        string database,
        string collectionName)
    {
        var dataBase = GetMongoDatabase(connectionString, database);
        var collection = dataBase.GetCollection<BsonDocument>(collectionName);
        return collection;
    }

    private static IMongoDatabase GetMongoDatabase(string connectionString, string database)
    {
        var mongoClient = new MongoClient(connectionString);
        var dataBase = mongoClient.GetDatabase(database);
        return dataBase;
    }
}
