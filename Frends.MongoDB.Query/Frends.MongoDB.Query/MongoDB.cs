using System.Collections.Generic;
using System.ComponentModel;
using System.Threading;
using Frends.MongoDB.Query.Definitions;
using Frends.MongoDB.Query.Helpers;
using MongoDB.Bson;
using MongoDB.Bson.IO;
using MongoDB.Driver;

namespace Frends.MongoDB.Query;

/// <summary>
/// MongoDB Task.
/// </summary>
public static class MongoDB
{
    /// <summary>
    /// Executes a MongoDB query.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.MongoDB.Query).
    /// </summary>
    /// <param name="input">Input parameters.</param>
    /// <param name="connection">Connection parameters.</param>
    /// <param name="options">Additional parameters.</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this task.</param>
    /// <returns>object { bool Success, List&lt;string&gt; Data, object Error { string Message, Exception AdditionalInfo } }.</returns>
    public static Result Query(
        [PropertyTab] Input input,
        [PropertyTab] Connection connection,
        [PropertyTab] Options options,
        CancellationToken cancellationToken)
    {
        if (string.IsNullOrWhiteSpace(input.Filter))
        {
            return new Exception("Query error: Filter can't be null.").Handle(options);
        }

        try
        {
            var collection = GetMongoCollection(
                connection.ConnectionString,
                connection.Database,
                connection.CollectionName);
            var cursor = collection.Find(input.Filter).ToCursor(cancellationToken);
            var jsonSettings = new JsonWriterSettings { OutputMode = JsonOutputMode.CanonicalExtendedJson };
            var documents = new List<string>();

            foreach (var document in cursor.ToEnumerable(cancellationToken: cancellationToken))
            {
                documents.Add(document.ToJson(jsonSettings));
            }

            return new Result
            {
                Success = true,
                Data = documents,
                Error = null,
            };
        }
        catch (Exception ex)
        {
            if (ex is OperationCanceledException)
            {
                return ex.Handle(options);
            }

            return new Exception($"Query error: {ex}").Handle(options);
        }
    }

    private static IMongoCollection<BsonDocument> GetMongoCollection(
        string connectionString,
        string database,
        string collectionName)
    {
        var dataBase = GetMongoDatabase(connectionString, database);
        return dataBase.GetCollection<BsonDocument>(collectionName);
    }

    private static IMongoDatabase GetMongoDatabase(string connectionString, string database)
    {
        var mongoClient = new MongoClient(connectionString);
        return mongoClient.GetDatabase(database);
    }
}
